"""Regenerate the flash-resident dropdown/rules from the bundled zones.csv.

Source: https://github.com/nayarsystems/posix_tz_db/blob/master/zones.csv
Run from the project root: python tools/generate_timezones.py
"""

import csv
import json
from pathlib import Path

root = Path(__file__).resolve().parent.parent
with (root / "tools/zones.csv").open(newline="", encoding="utf-8") as source:
    zones = sorted(csv.reader(source))
assert len({name for name, _ in zones}) == len(zones)
assert any(name == "Etc/UTC" for name, _ in zones)
assert all(len(name) <= 48 and len(rule) <= 63 for name, rule in zones)
lines = [
    "// Generated by tools/generate_timezones.py; do not edit by hand.",
    "// Source: https://github.com/nayarsystems/posix_tz_db/blob/master/zones.csv",
    "#pragma once",
    "#include <pgmspace.h>",
    "static const char TIME_ZONE_DATA[] PROGMEM =",
]
lines.extend("  " + json.dumps(name + "\t" + rule + "\n") for name, rule in zones)
lines.append("  ;\n")
(root / "include/time_zones.h").write_text("\n".join(lines), encoding="utf-8")
print(f"Generated {len(zones)} named time zones")
